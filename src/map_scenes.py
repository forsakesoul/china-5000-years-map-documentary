def validate(story, snapshots_dir):
    """配置自检：引用的快照与政权名必须真实存在，避免渲染时静默丢层。

    检查范围包括主体配置、evolve（疆域衍化的前期快照）与 inset（欧亚小图），
    它们各自引用不同的 world_<year> 快照。
    """
    import json
    import os
    problems = []
    for i, (sc, cfg) in enumerate(zip(story, SCENES)):
        blocks = [cfg] + ([cfg['evolve']] if cfg.get('evolve') else [])
        blocks += ([cfg['inset']] if cfg.get('inset') else [])
        for b in blocks:
            src = b.get('src')
            if src is None:
                continue
            path = os.path.join(snapshots_dir, f'world_{src}.geojson')
            if not os.path.exists(path):
                problems.append(f'场景{i}: 快照缺失 world_{src}.geojson')
                continue
            names = {f['properties'].get('NAME')
                     for f in json.load(open(path))['features']}
            shapes = b.get('shapes') or cfg.get('shapes') or {}

            def known(n):
                return n in names or (n.startswith('@') and n[1:] in shapes)
            for key in ('primary', 'accent', 'neutral'):
                for n in b.get(key) or []:
                    if not known(n):
                        problems.append(
                            f'场景{i}({src}): {key} 里的 {n!r} 不在 world_{src} 中')
            for g in b.get('groups') or []:
                for n in g['units'] + (g.get('minus') or []):
                    if not known(n):
                        problems.append(
                            f'场景{i}({src}): groups 里的 {n!r} 不在 world_{src} 中')
            for u in b.get('units') or []:
                unit = u[0] if isinstance(u, (tuple, list)) else u
                if unit not in names:
                    problems.append(
                        f'场景{i}({src}): inset units 里的 {unit!r} 不在 world_{src} 中')
            if b.get('voronoi'):
                for n in b['voronoi']['units'] + (b['voronoi'].get('minus') or []):
                    if not known(n):
                        problems.append(
                            f'场景{i}({src}): voronoi 里的 {n!r} 不在 world_{src} 中')
        for c in cfg.get('cities') or []:
            if c not in CITIES:
                problems.append(f'场景{i}: 城市 {c!r} 无坐标')
        for s in cfg.get('sites') or []:
            if s not in CITIES:
                problems.append(f'场景{i}: 光点 {s!r} 无坐标')
    return problems


